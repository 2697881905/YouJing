/**
 * Prompt/Schema 同源同步脚本。
 *
 * 单一事实源（SOT）在 entry/ 侧：
 *   entry/src/main/ets/ai/PromptBuilder.ets
 *   entry/src/main/ets/ai/TripSchema.ets
 *   entry/src/main/ets/utils/DateUtils.ets
 *   entry/src/main/ets/model/{PlanParams,Spot,Area}.ets（仅类型，供 tsc 解析）
 *
 * 本脚本把 SOT 用 DevEco 内置 tsc 转成 CommonJS，落到 bff/src/prompt/generated/。
 * BFF 运行期只加载生成物，不在 BFF 手写第二份规则或 Schema。
 *
 * 用法：
 *   npm run sync:prompt
 *   或 TSC=/path/to/tsc node scripts/sync-prompt-contract.mjs
 *
 * 若 entry/ 侧 SOT 改动，必须重跑本脚本；npm test 里的 hash 校验会拦住漏同步。
 */

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const BFF_ROOT = join(SCRIPT_DIR, '..');
const REPO_ROOT = join(BFF_ROOT, '..');
const GENERATED_DIR = join(BFF_ROOT, 'src', 'prompt', 'generated');

const SOURCES = [
  ['entry/src/main/ets/ai/PromptBuilder.ets', 'ai/PromptBuilder.ts'],
  ['entry/src/main/ets/ai/TripSchema.ets', 'ai/TripSchema.ts'],
  ['entry/src/main/ets/utils/DateUtils.ets', 'utils/DateUtils.ts'],
  ['entry/src/main/ets/utils/TripLength.ets', 'utils/TripLength.ts'],
  ['entry/src/main/ets/model/PlanParams.ets', 'model/PlanParams.ts'],
  ['entry/src/main/ets/model/Spot.ets', 'model/Spot.ts'],
  ['entry/src/main/ets/model/Area.ets', 'model/Area.ts']
];

const OUTPUTS = [
  ['ai/PromptBuilder.js', 'ai/PromptBuilder.js', 'entry/src/main/ets/ai/PromptBuilder.ets'],
  ['ai/TripSchema.js', 'ai/TripSchema.js', 'entry/src/main/ets/ai/TripSchema.ets'],
  ['utils/DateUtils.js', 'utils/DateUtils.js', 'entry/src/main/ets/utils/DateUtils.ets'],
  ['utils/TripLength.js', 'utils/TripLength.js', 'entry/src/main/ets/utils/TripLength.ets']
];

function sha256File(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex');
}

function findTsc() {
  const candidates = [
    process.env.TSC,
    '/Applications/DevEco-Studio.app/Contents/tools/ohpm/node_modules/typescript/bin/tsc',
    join(BFF_ROOT, 'node_modules', '.bin', 'tsc'),
    join(REPO_ROOT, 'node_modules', '.bin', 'tsc'),
    'tsc'
  ].filter(Boolean);
  for (const candidate of candidates) {
    if (candidate === 'tsc') {
      return candidate;
    }
    if (existsSync(candidate)) {
      return candidate;
    }
  }
  return null;
}

function autoHeader(source) {
  return `/* AUTO-GENERATED from ${source} by bff/scripts/sync-prompt-contract.mjs. Do not edit. */\n`;
}

function main() {
  const tsc = findTsc();
  if (!tsc) {
    console.error('sync-prompt: 找不到 tsc。请设置 TSC 环境变量，或在 DevEco 环境运行。');
    process.exit(1);
  }

  const temp = join(tmpdir(), `youjing-prompt-${Date.now()}`);
  const outDir = join(temp, 'out');
  mkdirSync(temp, { recursive: true });

  for (const [source, dest] of SOURCES) {
    const sourcePath = join(REPO_ROOT, source);
    if (!existsSync(sourcePath)) {
      console.error(`sync-prompt: 缺少 SOT 文件 ${source}`);
      process.exit(1);
    }
    const destPath = join(temp, dest);
    mkdirSync(dirname(destPath), { recursive: true });
    copyFileSync(sourcePath, destPath);
  }

  const compile = spawnSync(tsc, [
    '--strict',
    '--target', 'ES2020',
    '--module', 'commonjs',
    '--moduleResolution', 'node',
    '--outDir', outDir,
    join(temp, 'ai', 'PromptBuilder.ts')
  ], { encoding: 'utf8' });

  if (compile.status !== 0) {
    console.error('sync-prompt: tsc 编译失败');
    console.error(compile.stdout || '');
    console.error(compile.stderr || '');
    process.exit(compile.status || 1);
  }

  rmSync(GENERATED_DIR, { recursive: true, force: true });
  mkdirSync(GENERATED_DIR, { recursive: true });

  for (const [generated, target, source] of OUTPUTS) {
    const sourcePath = join(outDir, generated);
    if (!existsSync(sourcePath)) {
      console.error(`sync-prompt: tsc 未产出 ${generated}`);
      process.exit(1);
    }
    const body = readFileSync(sourcePath, 'utf8');
    const targetPath = join(GENERATED_DIR, target);
    mkdirSync(dirname(targetPath), { recursive: true });
    writeFileSync(targetPath, autoHeader(source) + body);
  }

  writeFileSync(join(GENERATED_DIR, 'package.json'), JSON.stringify({
    type: 'commonjs',
    _comment: 'AUTO-GENERATED by bff/scripts/sync-prompt-contract.mjs; kept so Node treats .js here as CommonJS.'
  }, null, 2) + '\n');

  // P1 AGC 云函数（无自购服务器）：把同一份生成物复制到 cloud/pickSpots/prompt，
  // 云端只 require 生成物，不手写第二份规则。改 entry/ SOT 后重跑本脚本即可同步。
  const cloudPromptDir = join(REPO_ROOT, 'cloud', 'pickSpots', 'prompt');
  rmSync(cloudPromptDir, { recursive: true, force: true });
  for (const [generated] of OUTPUTS) {
    const src = join(GENERATED_DIR, generated);
    const dest = join(cloudPromptDir, generated);
    mkdirSync(dirname(dest), { recursive: true });
    copyFileSync(src, dest);
  }
  writeFileSync(join(cloudPromptDir, 'package.json'), JSON.stringify({
    type: 'commonjs',
    _comment: 'AUTO-GENERATED by bff/scripts/sync-prompt-contract.mjs. Do not edit.'
  }, null, 2) + '\n');
  console.log(`sync-prompt: cloud copy → ${relative(REPO_ROOT, cloudPromptDir)}`);

  const sourceHashes = {};
  for (const [source] of SOURCES) {
    sourceHashes[source] = sha256File(join(REPO_ROOT, source));
  }
  const outputHashes = {};
  for (const [, target] of OUTPUTS) {
    outputHashes[target] = sha256File(join(GENERATED_DIR, target));
  }
  const version = spawnSync(tsc, ['--version'], { encoding: 'utf8' });
  const manifest = {
    _comment: 'AUTO-GENERATED by bff/scripts/sync-prompt-contract.mjs. Run npm run sync:prompt after changing entry/ SOT.',
    generatedAt: new Date().toISOString(),
    tsc: (version.stdout || '').trim(),
    sources: sourceHashes,
    outputs: outputHashes
  };
  writeFileSync(join(GENERATED_DIR, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

  console.log(`sync-prompt: OK (${relative(REPO_ROOT, GENERATED_DIR)})`);
  for (const [source] of SOURCES) {
    console.log(`  source ${source}`);
  }
  rmSync(temp, { recursive: true, force: true });
}

main();
